import { test, expect } from '@playwright/test';
test('New appointment sheet opens MIA and modal booking completes in the appointment list', async ({ page }, info) => {
  await page.goto('/'); await page.locator('.robot-launcher').click();
  await page.getByRole('button', { name: 'Thu gọn hướng dẫn', exact: true }).click();
  await page.getByRole('button', { name: 'Đặt lịch', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Đặt lịch hẹn' })).toBeVisible();
  await page.getByRole('button', { name: 'Tham vấn tâm lý từ xa', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('Chưa kết nối');
  await page.getByRole('button', { name: 'Đóng', exact: true }).click();
  await page.getByRole('button', { name: 'Đặt lịch', exact: true }).click();
  await page.getByRole('button', { name: 'Khám chuyên khoa tại bệnh viện', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Trợ lý sức khỏe AI MIA' })).toBeVisible();
  await expect(page.locator('.mia-character')).toBeVisible();
  await expect.poll(() => page.locator('.mia-character').evaluate(img => img.naturalWidth)).toBeGreaterThan(0);
  await page.screenshot({ path: `artifacts/mia-home-${info.project.name}.png`, fullPage: true });
  await page.getByRole('button', { name: 'Đặt lịch khám', exact: true }).first().click();
  await page.getByRole('button', { name: 'Chọn cơ sở khám', exact: true }).click();
  await page.getByRole('button', { name: 'Vinmec Times City', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận', exact: true }).click();
  await page.getByRole('button', { name: 'Tiếp theo', exact: true }).click();
  await page.getByRole('button', { name: 'Chọn chuyên khoa', exact: true }).click();
  await page.getByRole('button', { name: 'Tim mạch', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận', exact: true }).click();
  await page.getByRole('button', { name: 'Chọn bác sĩ', exact: true }).click();
  await page.getByRole('button', { name: /BS\. Nguyễn Minh Lan/ }).click();
  await page.getByRole('button', { name: 'Xác nhận', exact: true }).click();
  await page.getByRole('button', { name: 'Chọn thời gian khám', exact: true }).click();
  await page.locator('.mia-calendar [data-mia-date]').first().click();
  await expect(page.getByRole('button', { name: '10:00', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: '09:00', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận', exact: true }).click();
  await page.getByRole('button', { name: 'Tiếp theo', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('BS. Nguyễn Minh Lan');
  await page.screenshot({ path: `artifacts/mia-review-${info.project.name}.png`, fullPage: true });
  await expect(page.getByRole('button', { name: 'Xác nhận đặt lịch', exact: true })).toBeDisabled();
  await page.getByLabel('Tôi đồng ý với điều khoản sử dụng mẫu').check();
  await page.getByLabel('Tôi đồng ý với chính sách bảo mật mẫu').check();
  await page.getByRole('button', { name: 'Xác nhận đặt lịch', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('Chờ xác nhận');
  await page.getByRole('button', { name: 'Xem lịch hẹn', exact: true }).click();
  await expect(page.locator('.appointment-card')).toContainText('Tim mạch');
});

test('MIA reference tools give clear boundaries and manual form validates inputs', async ({ page }) => {
  await page.goto('/'); await page.locator('.robot-launcher').click();
  await page.getByRole('button', { name: 'Thu gọn hướng dẫn', exact: true }).click();
  await page.getByRole('button', { name: 'Trợ lý sức khỏe AI MIA', exact: true }).click();
  await page.getByRole('button', { name: 'Kiểm tra triệu chứng', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('không chẩn đoán');
  await page.getByRole('button', { name: 'Đóng', exact: true }).click();
  await page.getByRole('button', { name: 'Quay lại trang chủ', exact: true }).click();
  await page.getByRole('button', { name: 'Đặt lịch', exact: true }).click();
  await page.getByRole('button', { name: 'Đặt hẹn theo mẫu', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Đặt lịch hẹn', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'ĐẶT HẸN', exact: true })).toBeDisabled();
  await page.getByLabel('Cơ sở khám').selectOption('times');
  await page.getByLabel('Chuyên khoa').selectOption('general');
  await page.getByLabel('Ngày khám').selectOption({ index: 1 });
  await page.getByLabel('Giờ khám').selectOption('09:00');
  await page.getByRole('button', { name: 'ĐẶT HẸN', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('Xác nhận thông tin');
});

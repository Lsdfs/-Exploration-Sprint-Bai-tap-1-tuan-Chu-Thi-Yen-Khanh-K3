import {mockRealtime} from './realtime-helper.mjs';
import {test,expect} from '@playwright/test';
test('Floating Mia opens the reference page, then voice uses the reference form',async({page},info)=>{
 await mockRealtime(page);
 await page.goto('/');await page.locator('.robot-launcher').click();
 await expect(page.locator('#app')).toHaveClass(/mia-fullscreen/);
 await expect(page.getByRole('heading',{name:'Trợ lý sức khỏe AI MIA',exact:true})).toBeVisible();
 await expect(page.locator('.mia-tools>button')).toHaveCount(4);
 await expect(page.locator('.chatbot-header')).not.toContainText('Mia · Trợ lý của bạn');
 const panel=await page.locator('.chatbot-panel').boundingBox();expect(panel.width).toBeGreaterThan(Math.min(700,page.viewportSize().width-20));
 await page.screenshot({path:`artifacts/mia-matched-home-${info.project.name}.png`});
 await page.getByRole('button',{name:'Nói với Mia',exact:true}).click();
 await page.evaluate(()=>window.__mia.onresult({results:[[{transcript:'Tôi muốn đặt lịch khám'}]]}));
 await expect(page.locator('#mia-dialog')).toBeVisible();
 await expect(page.locator('#mia-dialog')).toContainText('Thông tin cơ bản');
 await expect(page.locator('#mia-profile')).toBeVisible();
 await expect(page.locator('#mia-dialog .voice-button')).toBeVisible();
 await page.screenshot({path:`artifacts/mia-matched-basics-${info.project.name}.png`});
 await page.locator('#help-question').fill('Đặt cho mẹ khám tim tại Times City ngày mai chín giờ, không chọn bác sĩ cụ thể');
 await page.locator('.send-button').click();
 await expect(page.locator('#mia-dialog')).toContainText('Xác nhận thông tin');
 await expect(page.locator('#mia-dialog')).toContainText('Bác Bình');
 await expect(page.locator('#mia-dialog')).toContainText('09:00');
 await page.screenshot({path:`artifacts/mia-matched-review-${info.project.name}.png`});
});
test('Reference form keeps typed selections when voice completes booking and confirms',async({page})=>{
 await page.goto('/');await page.locator('.robot-launcher').click();
 await page.locator('[data-mia="book"]').click();
 await page.locator('#mia-profile').selectOption('family');
 await page.locator('[data-mia="pick-location"]').click();
 await page.locator('[data-mia-value="central"]').click();await page.locator('[data-mia="picker-confirm"]').click();
 await page.locator('#help-question').fill('Khám tổng quát ngày mai chín giờ, không chọn bác sĩ cụ thể');
 await page.locator('.send-button').click();
 await expect(page.locator('#mia-dialog')).toContainText('Xác nhận thông tin');
 await expect(page.locator('#mia-dialog')).toContainText('Bác Bình');
 await expect(page.locator('#mia-dialog')).toContainText('Central Park');
 await page.locator('#mia-terms').check();await page.locator('#mia-privacy').check();
 await page.locator('[data-mia="confirm"]').click();
 await expect(page.locator('#mia-dialog')).toContainText('Chờ xác nhận');
 await page.locator('[data-mia="appointments"]').click();
 await expect(page.locator('.appointment-card')).toContainText('Bác Bình');
});
